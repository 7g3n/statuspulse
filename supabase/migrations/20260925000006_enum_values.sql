-- StatusPulse / Phase 4 の準備: enum への値の追加だけを行う
--
-- **なぜこのファイルだけ分かれているのか**
--   `alter type ... add value` で追加した値は、**同じトランザクションの中では使えない**
--   （Postgres の制約。追加自体は PG12 以降トランザクション内で可能になったが、
--    直後に参照すると "unsafe use of new value" で失敗する）。
--
--   マイグレーションは1ファイル1トランザクションで流れるので、
--   値の追加と、その値を使う定義（CHECK 制約や関数の既定値など）を
--   同じファイルに書くことができない。
--
--   将来ここに値を足すときも、同じ理由でこのファイルに寄せる。
-- =============================================================================

-- 応答は返ったが、本文に期待する文字列が含まれていなかった。
